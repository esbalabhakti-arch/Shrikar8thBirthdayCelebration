const gallery = document.getElementById("gallery");
const emptyState = document.getElementById("emptyState");
const lightbox = document.getElementById("lightbox");
const lightboxStage = document.getElementById("lightboxStage");
const lightboxCaption = document.getElementById("lightboxCaption");
const filterButtons = [...document.querySelectorAll(".filter-button")];

let activeFilter = "all";
let visibleItems = [...mediaItems];
let currentIndex = 0;
let lastFocusedElement = null;

const featuredVideo = mediaItems.find(item => item.featured) || mediaItems.find(item => item.type === "video");
const heroPhoto = mediaItems.find(item => item.type === "image");

function encodePath(path) {
  return path.split("/").map(encodeURIComponent).join("/");
}

function friendlyLabel(item, index) {
  if (item.featured) return "Birthday highlight";
  return item.type === "video" ? `Birthday video ${index + 1}` : `Birthday photo ${index + 1}`;
}

function setHeroImage() {
  if (!heroPhoto) return;
  document.getElementById("heroCard").style.setProperty("--hero-image", `url("${encodePath(heroPhoto.src)}")`);
}

function updateCounts() {
  const photos = mediaItems.filter(item => item.type === "image").length;
  const videos = mediaItems.filter(item => item.type === "video").length;
  document.getElementById("photoCount").textContent = `${photos} Photos`;
  document.getElementById("videoCount").textContent = `${videos} Videos`;
}

function makeCard(item, index) {
  const card = document.createElement("button");
  card.type = "button";
  card.className = "media-card";
  card.setAttribute("aria-label", `Open ${friendlyLabel(item, index)}`);

  // A varied mosaic pattern without altering the original image proportions.
  if (index % 11 === 0 || item.featured) card.classList.add("wide");
  if (item.type === "image" && (index % 9 === 3 || index % 13 === 7)) card.classList.add("tall");

  const path = encodePath(item.src);
  if (item.type === "image") {
    const image = document.createElement("img");
    image.src = path;
    image.alt = friendlyLabel(item, index);
    image.loading = index < 8 ? "eager" : "lazy";
    image.decoding = "async";
    card.appendChild(image);
  } else {
    const video = document.createElement("video");
    video.src = path;
    video.muted = true;
    video.preload = "metadata";
    video.playsInline = true;
    card.appendChild(video);

    const playIcon = document.createElement("span");
    playIcon.className = "play-icon";
    playIcon.textContent = "▶";
    playIcon.setAttribute("aria-hidden", "true");
    card.appendChild(playIcon);
  }

  const badge = document.createElement("span");
  badge.className = "media-badge";
  badge.textContent = item.type === "video" ? "🎬 Video" : "📷 Photo";
  card.appendChild(badge);

  if (item.featured) {
    const ribbon = document.createElement("span");
    ribbon.className = "featured-ribbon";
    ribbon.textContent = "⭐ Highlight";
    card.appendChild(ribbon);
  }

  card.addEventListener("click", () => openLightbox(index));
  return card;
}

function renderGallery() {
  visibleItems = mediaItems.filter(item => activeFilter === "all" || item.type === activeFilter);
  gallery.replaceChildren();
  emptyState.hidden = visibleItems.length > 0;

  const fragment = document.createDocumentFragment();
  visibleItems.forEach((item, index) => fragment.appendChild(makeCard(item, index)));
  gallery.appendChild(fragment);
}

function openLightbox(index) {
  if (!visibleItems.length) return;
  currentIndex = (index + visibleItems.length) % visibleItems.length;
  lastFocusedElement = document.activeElement;
  showCurrentItem();
  lightbox.classList.add("open");
  lightbox.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  document.getElementById("lightboxClose").focus();
}

function showCurrentItem() {
  const item = visibleItems[currentIndex];
  const path = encodePath(item.src);
  lightboxStage.replaceChildren();

  if (item.type === "image") {
    const image = document.createElement("img");
    image.src = path;
    image.alt = friendlyLabel(item, currentIndex);
    lightboxStage.appendChild(image);
  } else {
    const video = document.createElement("video");
    video.src = path;
    video.controls = true;
    video.autoplay = true;
    video.playsInline = true;
    lightboxStage.appendChild(video);
  }

  lightboxCaption.textContent = `${friendlyLabel(item, currentIndex)} · ${currentIndex + 1} of ${visibleItems.length}`;
}

function closeLightbox() {
  const playingVideo = lightboxStage.querySelector("video");
  if (playingVideo) playingVideo.pause();
  lightbox.classList.remove("open");
  lightbox.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  lightboxStage.replaceChildren();
  if (lastFocusedElement) lastFocusedElement.focus();
}

function moveLightbox(direction) {
  const playingVideo = lightboxStage.querySelector("video");
  if (playingVideo) playingVideo.pause();
  currentIndex = (currentIndex + direction + visibleItems.length) % visibleItems.length;
  showCurrentItem();
}

filterButtons.forEach(button => {
  button.addEventListener("click", () => {
    activeFilter = button.dataset.filter;
    filterButtons.forEach(item => item.classList.toggle("active", item === button));
    renderGallery();
  });
});

document.getElementById("shuffleButton").addEventListener("click", () => {
  for (let i = mediaItems.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [mediaItems[i], mediaItems[j]] = [mediaItems[j], mediaItems[i]];
  }
  renderGallery();
});

document.getElementById("playFeatured").addEventListener("click", () => {
  if (!featuredVideo) return;
  activeFilter = "all";
  filterButtons.forEach(button => button.classList.toggle("active", button.dataset.filter === "all"));
  renderGallery();
  const featuredIndex = visibleItems.findIndex(item => item.src === featuredVideo.src);
  openLightbox(featuredIndex);
});

document.getElementById("lightboxClose").addEventListener("click", closeLightbox);
document.getElementById("lightboxPrev").addEventListener("click", () => moveLightbox(-1));
document.getElementById("lightboxNext").addEventListener("click", () => moveLightbox(1));

lightbox.addEventListener("click", event => {
  if (event.target === lightbox) closeLightbox();
});

document.addEventListener("keydown", event => {
  if (!lightbox.classList.contains("open")) return;
  if (event.key === "Escape") closeLightbox();
  if (event.key === "ArrowLeft") moveLightbox(-1);
  if (event.key === "ArrowRight") moveLightbox(1);
});

// Basic swipe navigation for phones and tablets.
let touchStartX = 0;
lightbox.addEventListener("touchstart", event => {
  touchStartX = event.changedTouches[0].screenX;
}, { passive: true });
lightbox.addEventListener("touchend", event => {
  const distance = event.changedTouches[0].screenX - touchStartX;
  if (Math.abs(distance) > 55) moveLightbox(distance > 0 ? -1 : 1);
}, { passive: true });

function addConfetti() {
  const container = document.getElementById("confetti");
  const colors = ["#6c4cff", "#ff4f9a", "#ffd84d", "#20c9d8", "#ff7a45"];
  const fragment = document.createDocumentFragment();

  for (let i = 0; i < 32; i++) {
    const piece = document.createElement("span");
    piece.style.left = `${Math.random() * 100}%`;
    piece.style.background = colors[i % colors.length];
    piece.style.animationDuration = `${8 + Math.random() * 10}s`;
    piece.style.animationDelay = `${-Math.random() * 18}s`;
    piece.style.setProperty("--drift", `${-90 + Math.random() * 180}px`);
    piece.style.transform = `rotate(${Math.random() * 360}deg)`;
    fragment.appendChild(piece);
  }
  container.appendChild(fragment);
}

setHeroImage();
updateCounts();
renderGallery();
addConfetti();
